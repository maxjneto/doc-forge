const dictionaries: Record<Locale, Messages> = { en, "pt-BR": ptBR };

export function normalizeLocale(value?: string | null): Locale {
  return value?.toLowerCase().startsWith("pt") ? "pt-BR" : "en";
}

export function translate(locale: Locale, key: string, variables?: Variables): string {
  const template = dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
  if (!variables) return template;
  return template.replace(/{{(\w+)}}/g, (_, name: string) => String(variables[name] ?? `{{${name}}}`));
}

interface I18nValue {
  locale: Locale;
  dateLocale: string;
  setLocale: (locale: Locale) => void;
  t: (key: string, variables?: Variables) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

function initialLocale(): Locale {
  if (typeof window === "undefined") return "en";
  return normalizeLocale(window.localStorage.getItem(STORAGE_KEY) ?? window.navigator.language);
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocale] = useState<Locale>(initialLocale);

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, locale);
    document.documentElement.lang = locale;
  }, [locale]);

  const value = useMemo<I18nValue>(() => ({
    locale,
    dateLocale: locale === "pt-BR" ? "pt-BR" : "en-US",
    setLocale,
    t: (key, variables) => translate(locale, key, variables),
  }), [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}
